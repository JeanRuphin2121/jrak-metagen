package io.metagen.core.domain;

import com.fasterxml.jackson.databind.JsonNode;
import io.hypersistence.utils.hibernate.type.json.JsonType;
import jakarta.persistence.*;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;
import lombok.*;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.Type;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.Instant;
import java.util.UUID;

/**
 * A named, configurable view for a {@link MetaEntity}.
 *
 * <p>Each entity automatically gets default LIST and FORM views generated by
 * the engine. {@code MetaView} allows overriding or adding custom views with
 * precise configuration stored in the {@code config} JSONB field.</p>
 *
 * <h2>Config structure by type</h2>
 * <pre>
 * LIST view:
 * {
 *   "columns":  ["name", "status", "created_at"],
 *   "filters":  [{ "field": "status", "operator": "eq" }],
 *   "pageSize": 25,
 *   "defaultSort": { "field": "created_at", "direction": "DESC" }
 * }
 *
 * KANBAN view:
 * {
 *   "groupBy":    "status",      // must be an ENUM or workflow state field
 *   "cardFields": ["name", "assignee", "due_date"],
 *   "swimlane":   "category"     // optional secondary grouping
 * }
 *
 * CHART view:
 * {
 *   "chartType": "bar",          // bar | pie | line | area
 *   "metric":    "count",        // count | sum | avg
 *   "dimension": "status",
 *   "measure":   "amount"        // for sum/avg
 * }
 * </pre>
 */
@Entity
@Table(
    name = "meta_view",
    uniqueConstraints = @UniqueConstraint(
        name = "uq_meta_view_name",
        columnNames = "name"
    )
)
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class MetaView {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(updatable = false, nullable = false)
    private UUID id;

    /**
     * Technical name in snake_case.
     * Example: {@code supplier_list}, {@code order_kanban}.
     */
    @NotBlank
    @Size(max = 100)
    @Pattern(regexp = "^[a-z][a-z0-9_]*$",
             message = "name must be lowercase snake_case")
    @Column(nullable = false, length = 100)
    private String name;

    /** Human-readable label shown in navigation and tab headers. */
    @NotBlank
    @Size(max = 200)
    @Column(nullable = false, length = 200)
    private String label;

    /**
     * The entity this view displays data from.
     * May be {@code null} for DASHBOARD views that aggregate multiple entities.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(
        name = "entity_id",
        foreignKey = @ForeignKey(name = "fk_view_entity")
    )
    private MetaEntity entity;

    /** Type of view component to render. */
    @NotNull
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 50)
    private MetaViewType type;

    /**
     * View-specific rendering configuration.
     * Structure depends on {@link #type} — see class-level Javadoc.
     */
    @Builder.Default
    @Type(JsonType.class)
    @Column(columnDefinition = "jsonb", nullable = false)
    private JsonNode config = com.fasterxml.jackson.databind.node.JsonNodeFactory.instance.objectNode();

    /**
     * Whether this is the default view for the entity+type combination.
     * Only one view per entity/type pair should have {@code defaultView = true}.
     */
    @Builder.Default
    @Column(name = "is_default", nullable = false)
    private boolean defaultView = false;

    @CreationTimestamp
    @Column(name = "created_at", updatable = false, nullable = false)
    private Instant createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;
}
